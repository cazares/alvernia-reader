/**
 * Generate a Metro-friendly static asset map for an offline book bundle.
 *
 * We need static `require("...")` calls so Metro includes the images in the app bundle.
 *
 * Usage:
 *   node scripts/gen-offline-book-asset-map.mjs --id hymns-1 --dir assets/offline-books/hymns-1 --out src/offlineBookAssets.hymns-1.js
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, "..");

const args = process.argv.slice(2);
const getArg = (name) => {
  const idx = args.indexOf(name);
  if (idx === -1) return null;
  return args[idx + 1] ?? null;
};

const id = getArg("--id");
const dirRel = getArg("--dir");
const outRel = getArg("--out");
if (!id || !dirRel || !outRel) {
  console.error("Missing args: --id <id> --dir <bundleDir> --out <outFile>");
  process.exit(2);
}

const bundleDir = path.resolve(rootDir, dirRel);
const outFile = path.resolve(rootDir, outRel);

const listFiles = (subdir) => {
  const abs = path.join(bundleDir, subdir);
  if (!fs.existsSync(abs)) return [];
  return fs
    .readdirSync(abs)
    .filter((f) => f.endsWith(".jpg"))
    .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }))
    .map((f) => `${subdir}/${f}`);
};

const pageFiles = listFiles("pages");
const thumbFiles = listFiles("thumbs");
if (!pageFiles.length) {
  console.error(`No pages/*.jpg found in ${dirRel}`);
  process.exit(2);
}

const relRequireBase = `../${dirRel}`.replace(/\\/g, "/");

const lines = [];
lines.push(`// Generated by scripts/gen-offline-book-asset-map.mjs for ${id}`);
lines.push(`const BOOK_ID = ${JSON.stringify(id)};`);
lines.push("");
lines.push("const ASSETS = {");
for (const relPath of [...pageFiles, ...thumbFiles]) {
  lines.push(`  ${JSON.stringify(relPath)}: require(${JSON.stringify(`${relRequireBase}/${relPath}`)}),`);
}
lines.push("};");
lines.push("");
lines.push("module.exports = { BOOK_ID, ASSETS };");
lines.push("");

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, lines.join("\n"));
console.log(`Wrote ${path.relative(rootDir, outFile)}`);
